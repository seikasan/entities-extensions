using System;
using System.IO;
using System.Security.Cryptography;
using System.Text;

namespace Entities.Authoring.Editor
{
    internal static class AuthoringFileWriter
    {
        internal const string Marker = "// <auto-generated by Entities.Authoring>";
        private const string OwnerPrefix = "// Owner: ";
        private const string HashPrefix = "// ContentHash: ";
        private const string End = "// </auto-generated>\n";

        private static string Normalize(string value) => value.Replace("\r\n", "\n").Replace('\r', '\n');

        private static string Hash(string value)
        {
            using var sha = SHA256.Create();

            return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(value))).Replace("-", "").ToLowerInvariant();
        }

        internal static string ReadOwner(string path)
        {
            if (!File.Exists(path)) return null;

            using var reader = File.OpenText(path);

            if (reader.ReadLine() != Marker) return null;

            string owner = reader.ReadLine();

            return owner != null && owner.StartsWith(OwnerPrefix, StringComparison.Ordinal)
                ? owner[OwnerPrefix.Length..]
                : null;
        }

        internal static string EncodeOwner(string owner) => Convert.ToBase64String(Encoding.UTF8.GetBytes(owner));

        internal static bool Write(
            string path,
            string owner,
            string source,
            bool allowWrite = true)
        {
            string body = Normalize(source);
            string encodedOwner = EncodeOwner(owner);
            string content = Marker + "\n" + OwnerPrefix + encodedOwner + "\n" + HashPrefix + Hash(body) + "\n" + End + body;
            string previous = null;

            if (File.Exists(path))
            {
                previous = File.ReadAllText(path);
                string normalized = Normalize(previous);
                var lines = normalized.Split('\n');
                int end = normalized.IndexOf(End, StringComparison.Ordinal);

                if (lines.Length < 4 ||
                    lines[0] != Marker ||
                    lines[1] != OwnerPrefix + encodedOwner ||
                    !lines[2].StartsWith(HashPrefix, StringComparison.Ordinal) ||
                    end < 0)
                {
                    throw new InvalidOperationException("AEA004 " + path + ": A handwritten/different-owner file occupies the destination. Move it or resolve the name collision; it will not be overwritten.");
                }

                string existingBody = normalized.Substring(end + End.Length);

                if (lines[2].Substring(HashPrefix.Length) != Hash(existingBody))
                {
                    throw new InvalidOperationException("AEA004 " + path + ": The generated file was manually edited. Preserve your edits and restore the generated version before synchronizing; it will not be overwritten.");
                }

                if (normalized == content) return false;

                if ((File.GetAttributes(path) & FileAttributes.ReadOnly) != 0)
                {
                    throw new UnauthorizedAccessException("AEA006 " + path + ": Destination is read-only. Make the source package/file writable.");
                }
            }

            if (!allowWrite)
            {
                throw new UnauthorizedAccessException("AEA006 " + path + ": Source/target package is read-only. Embed it or use a writable local package before generating or updating authoring.");
            }

            string temporary = path + "." + Guid.NewGuid().ToString("N") + ".aea.tmp";
            try
            {
                File.WriteAllText(
                    temporary,
                    content,
                    new UTF8Encoding(false));
                if (previous == null)
                {
                    File.Move(temporary, path);
                }
                else
                {
                    string current = File.ReadAllText(path);

                    if (current != previous)
                    {
                        if (Normalize(current) == content) return false;

                        throw new InvalidOperationException("AEA004 " + path + ": File changed during synchronization. Retry after saving your edits.");
                    }

                    File.Replace(
                        temporary,
                        path,
                        null);
                }
            }
            catch (IOException)
                when (File.Exists(path) && Normalize(File.ReadAllText(path)) == content)
            {
                return false;
            }
            finally
            {
                if (File.Exists(temporary))
                {
                    File.Delete(temporary);
                }
            }

            return true;
        }
    }
}
