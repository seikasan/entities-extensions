using System.Text;

namespace Entities.Authoring.Generator
{
    internal static class MetadataEmitter
    {
        internal static string Authoring(ComponentModel model)
        {
            var code = new StringBuilder("#pragma warning disable 0649\n");
            string indent = model.Namespace.Length == 0 ? "" : "    ";
            if (model.Namespace.Length != 0)
            {
                code.Append("namespace ").Append(Code.CodeNamespace(model.Namespace)).Append("\n{\n");
            }

            code.Append(indent).Append("public partial class ").Append(Code.Identifier(model.AuthoringName)).Append(" : global::UnityEngine.MonoBehaviour\n").Append(indent).Append("{\n");
            if (model.IsBuffer)
            {
                // 要素ごとのシリアライズ可能なクラスを生成し、Inspectorからリストで編集できるようにします。
                code.Append(indent).Append("    [global::System.Serializable]\n")
                    .Append(indent).Append("    private sealed class ").Append(Code.Identifier(model.BufferElementName)).Append("\n")
                    .Append(indent).Append("    {\n");
                foreach (var field in model.Fields)
                {
                    code.Append(indent).Append("        [global::UnityEngine.SerializeField]\n")
                        .Append(indent).Append("        public ").Append(field.AuthoringType).Append(' ')
                        .Append(Code.Identifier(field.Symbol.Name)).Append(field.Initializer).Append(";\n");
                }

                code.Append(indent).Append("    }\n")
                    .Append(indent).Append("    [global::UnityEngine.SerializeField, global::UnityEngine.InspectorName(\"Buffer Elements\")]\n")
                    .Append(indent).Append("    private global::System.Collections.Generic.List<")
                    .Append(Code.Identifier(model.BufferElementName)).Append("> ")
                    .Append(Code.Identifier(model.BufferListName))
                    .Append(" = new global::System.Collections.Generic.List<")
                    .Append(Code.Identifier(model.BufferElementName)).Append(">();\n");
            }
            else
            {
                foreach (var field in model.Fields)
                {
                    code.Append(indent).Append("    [global::UnityEngine.SerializeField]\n")
                        .Append(indent).Append("    private ").Append(field.AuthoringType).Append(' ')
                        .Append(Code.Identifier(field.Symbol.Name)).Append(field.Initializer).Append(";\n");
                }
            }

            if (model.EnabledField != null)
            {
                code.Append(indent).Append("    [global::UnityEngine.SerializeField, global::UnityEngine.InspectorName(\"Enabled\")]\n").Append(indent).Append("    private bool ").Append(Code.Identifier(model.EnabledField)).Append(" = true;\n");
            }

            code.Append(indent).Append("}\n");
            if (model.Namespace.Length != 0)
            {
                code.Append("}\n");
            }

            return code.ToString();
        }

        internal static string Emit(ComponentModel model) => "// <auto-generated/>\n#if UNITY_EDITOR\n[assembly: global::Entities.Authoring.AutoAuthoringMetadataAttribute(" + Code.Literal(model.MetadataName) + ", " + Code.Literal(model.SourcePath) + ", " + Code.Literal(model.AssemblyName) + ", " + Code.Literal(model.AuthoringType) + ", " + Code.Literal(Authoring(model)) + ")]\n#endif\n";
    }
}
