using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Entities.Authoring.Generator
{
    internal sealed class ComponentModel
    {
        public INamedTypeSymbol Symbol;
        public string Namespace;
        public string ComponentType;
        public string MetadataName;
        public string AuthoringName;
        public string AuthoringType;
        public string SourcePath;
        public string AssemblyName;
        public string EnabledField;
        public bool IsBuffer;
        public string BufferElementName;
        public string BufferListName;
        public int Flags;
        public readonly List<FieldModel> Fields = new List<FieldModel>();
    }

    internal sealed class FieldModel
    {
        public IFieldSymbol Symbol;
        public string AuthoringType;
        public string Initializer;
        public string Preparation;
        public string Value;
    }

    internal static class Code
    {
        internal const string Marker = "// <auto-generated by Entities.Authoring>";
        internal static string Identifier(string name) => SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None &&
            SyntaxFacts.GetContextualKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
        internal static string Literal(string value) => SymbolDisplay.FormatLiteral(value ?? "", true);
        internal static string Type(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        internal static string CodeNamespace(string value) => string.Join(".", value.Split('.').Select(Identifier));
        internal static string MetadataName(INamedTypeSymbol type)
        {
            string name = type.MetadataName;
            for (var parent = type.ContainingType; parent != null; parent = parent.ContainingType)
            {
                name = parent.MetadataName + "+" + name;
            }

            var names = new Stack<string>();
            for (var ns = type.ContainingNamespace; !ns.IsGlobalNamespace; ns = ns.ContainingNamespace)
            {
                names.Push(ns.Name);
            }

            return names.Count == 0 ? name : string.Join(".", names) + "." + name;
        }
    }
}
