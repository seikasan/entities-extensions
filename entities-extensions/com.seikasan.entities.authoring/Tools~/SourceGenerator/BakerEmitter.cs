using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Entities.Authoring.Generator
{
    internal static class BakerEmitter
    {
        internal static bool IsOwned(INamedTypeSymbol authoring) => authoring.DeclaringSyntaxReferences.Any(r => r.SyntaxTree.GetText().ToString().StartsWith(Code.Marker));
        internal static bool Matches(INamedTypeSymbol authoring, ComponentModel model)
        {
            if (!authoring.DeclaringSyntaxReferences.All(r => r.GetSyntax() is ClassDeclarationSyntax c &&
                c.Modifiers.Any(SyntaxKind.PartialKeyword)))
            {
                return false;
            }

            var fields = authoring.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic &&
                !f.IsImplicitlyDeclared).ToArray();

            if (model.IsBuffer)
            {
                if (fields.Length != 1 + (model.EnabledField == null ? 0 : 1))
                {
                    return false;
                }

                var list = fields.FirstOrDefault(f => f.Name == model.BufferListName);
                var listType = list?.Type as INamedTypeSymbol;
                var element = listType?.TypeArguments.FirstOrDefault() as INamedTypeSymbol;
                if (listType?.Name != "List" ||
                    listType.ContainingNamespace.ToDisplayString() != "System.Collections.Generic" ||
                    element?.Name != model.BufferElementName ||
                    element.TypeKind != TypeKind.Class ||
                    !element.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.SerializableAttribute") ||
                    !SymbolEqualityComparer.Default.Equals(element.ContainingType, authoring) ||
                    !list.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "UnityEngine.SerializeField"))
                {
                    return false;
                }

                var elementFields = element.GetMembers().OfType<IFieldSymbol>()
                    .Where(f => !f.IsStatic && !f.IsImplicitlyDeclared).ToArray();
                if (elementFields.Length != model.Fields.Count ||
                    !model.Fields.All(expected => elementFields.Any(actual =>
                        actual.Name == expected.Symbol.Name &&
                        Code.Type(actual.Type) == expected.AuthoringType &&
                        !actual.IsReadOnly &&
                        actual.DeclaredAccessibility == Accessibility.Public &&
                        actual.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "UnityEngine.SerializeField"))))
                {
                    return false;
                }
            }
            else if (fields.Length != model.Fields.Count + (model.EnabledField == null ? 0 : 1))
            {
                return false;
            }

            bool Field(string name, string type) => fields.Any(f => f.Name == name &&
                Code.Type(f.Type) == type &&
                !f.IsReadOnly &&
                f.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "UnityEngine.SerializeField"));

            return (model.IsBuffer || model.Fields.All(f => Field(f.Symbol.Name, f.AuthoringType))) &&
                (model.EnabledField == null || Field(model.EnabledField, "bool"));
        }

        internal static string Emit(ComponentModel model)
        {
            var code = new StringBuilder("// <auto-generated/>\n");
            string indent = model.Namespace.Length == 0 ? "" : "    ";
            if (model.Namespace.Length != 0)
            {
                code.Append("namespace ").Append(Code.CodeNamespace(model.Namespace)).Append("\n{\n");
            }

            code.Append(indent).Append("public partial class ").Append(Code.Identifier(model.AuthoringName)).Append("\n").Append(indent).Append("{\n").Append(indent).Append("    private sealed class Baker : global::Unity.Entities.Baker<").Append(Code.Identifier(model.AuthoringName)).Append(">\n").Append(indent).Append("    {\n").Append(indent).Append("        public override void Bake(").Append(Code.Identifier(model.AuthoringName)).Append(" authoring)\n").Append(indent).Append("        {\n");
            if (model.IsBuffer)
            {
                AppendBuffer(code, model, indent);
            }
            else
            {
                foreach (var field in model.Fields)
                {
                    if (field.Preparation == null)
                    {
                        continue;
                    }

                    foreach (string line in field.Preparation.TrimEnd('\n').Split('\n'))
                    {
                        if (line.Length != 0)
                        {
                            code.Append(indent).Append("            ").Append(line);
                        }

                        code.Append('\n');
                    }

                    code.Append('\n');
                }

                code.Append(indent).Append("            var entity = GetEntity((global::Unity.Entities.TransformUsageFlags)").Append(model.Flags).Append(");\n");
                if (model.Fields.Count == 0)
                {
                    code.Append(indent).Append("            AddComponent<").Append(model.ComponentType).Append(">(entity);\n");
                }
                else
                {
                    code.Append(indent).Append("            AddComponent(entity, new ").Append(model.ComponentType).Append("\n").Append(indent).Append("            {\n");
                    foreach (var field in model.Fields)
                    {
                        code.Append(indent).Append("                ").Append(Code.Identifier(field.Symbol.Name)).Append(" = ").Append(field.Value).Append(",\n");
                    }

                    code.Append(indent).Append("            });\n");
                }

            }

            if (model.EnabledField != null)
            {
                code.Append(indent).Append("            SetComponentEnabled<").Append(model.ComponentType).Append(">(entity, authoring.").Append(Code.Identifier(model.EnabledField)).Append(");\n");
            }

            code.Append(indent).Append("        }\n").Append(indent).Append("    }\n").Append(indent).Append("}\n");
            if (model.Namespace.Length != 0)
            {
                code.Append("}\n");
            }

            return code.ToString();
        }
        private static void AppendBuffer(StringBuilder code, ComponentModel model, string indent)
        {
            void Line(int depth, string value) => code.Append(indent).Append(' ', 12 + depth * 4)
                .Append(value).Append('\n');

            Line(0, "var __aeaElements = new global::System.Collections.Generic.List<" + model.ComponentType + ">();");
            Line(0, "if (authoring." + Code.Identifier(model.BufferListName) + " != null)");
            Line(0, "{");
            Line(1, "foreach (var __aeaItem in authoring." + Code.Identifier(model.BufferListName) + ")");
            Line(1, "{");
            Line(2, "if (__aeaItem == null)");
            Line(2, "{");
            Line(3, "global::UnityEngine.Debug.LogError(" +
                Code.Literal("AEA008 " + model.MetadataName + ": Bufferの要素がnullです。各要素を設定してください。") +
                ", authoring);");
            Line(3, "return;");
            Line(2, "}");

            foreach (var field in model.Fields)
            {
                if (field.Preparation == null)
                {
                    continue;
                }

                foreach (var line in field.Preparation.TrimEnd('\n').Split('\n'))
                {
                    Line(2, line);
                }
            }

            Line(2, "__aeaElements.Add(new " + model.ComponentType);
            Line(2, "{");
            foreach (var field in model.Fields)
            {
                Line(3, Code.Identifier(field.Symbol.Name) + " = " + field.Value + ",");
            }

            Line(2, "});");
            Line(1, "}");
            Line(0, "}");
            // 変換が失敗した場合はここへ到達しないため、中途半端なBufferをBakingしません。
            Line(0, "var entity = GetEntity((global::Unity.Entities.TransformUsageFlags)" + model.Flags + ");");
            Line(0, "var buffer = AddBuffer<" + model.ComponentType + ">(entity);");
            Line(0, "buffer.EnsureCapacity(__aeaElements.Count);");
            Line(0, "foreach (var __aeaElement in __aeaElements)");
            Line(0, "{");
            Line(1, "buffer.Add(__aeaElement);");
            Line(0, "}");
        }

    }
}
