            bufferComplete.Metadata.Contains("[global::System.Serializable]") &&
            bufferComplete.Baker.Contains("AddBuffer<global::Data>(entity)") &&
            bufferComplete.Baker.Contains("buffer.Add(__aeaElement)") &&
