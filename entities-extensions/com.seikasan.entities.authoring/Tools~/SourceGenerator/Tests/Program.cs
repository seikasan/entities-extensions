    private sealed class Result
    {
        public GeneratorDriverRunResult Run;
        public Compilation Compilation;
        public string Metadata => string.Join(
            "\n",
            Run.Results.SelectMany(r => r.GeneratedSources).Where(s => s.HintName.EndsWith(".Metadata.g.cs")).Select(s => s.SourceText.ToString()));
        public string Baker => string.Join(
            "\n",
            Run.Results.SelectMany(r => r.GeneratedSources).Where(s => s.HintName.EndsWith(".Baker.g.cs")).Select(s => s.SourceText.ToString()));
        public IEnumerable<string> AuthoringBodies => Run.GeneratedTrees.SelectMany(t => t.GetRoot().DescendantNodes().OfType<AttributeSyntax>()).Where(a => a.Name.ToString().Contains("AutoAuthoringMetadataAttribute")).Select(a => ((LiteralExpressionSyntax)a.ArgumentList.Arguments[4].Expression).Token.ValueText);
    }

    private static Result Run(
        string source,
        IEnumerable<string> authoring = null,
        string path = "Assets/Data.cs")
    {
        var trees = new List<SyntaxTree>
        {
            CSharpSyntaxTree.ParseText(
                Stubs,
                Options,
                "Stubs.cs"),
            CSharpSyntaxTree.ParseText(
                source,
                Options,
                path)
        };
        if (authoring != null)
        {
            trees.AddRange(authoring.Select((s, i) => CSharpSyntaxTree.ParseText(
                s,
                Options,
                "Assets/Authoring" + i + ".cs")));
        }

        var compilation = CSharpCompilation.Create(
            "Generator.Tests",
            trees,
            References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new[] { new AuthoringGenerator().AsSourceGenerator() }, parseOptions: Options);
        driver.RunGeneratorsAndUpdateCompilation(
            compilation,
            out var generated,
            out _);
        driver = driver.RunGeneratorsAndUpdateCompilation(
            compilation,
            out generated,
            out _);

        return new Result
        {
            Run = driver.GetRunResult(),
            Compilation = generated
        };
    }

    private static Result Complete(string source)
    {
        var initial = Run(source);

        return Run(source, initial.AuthoringBodies.Select(body => Marker + body));
    }

    private static string Component(
        string body,
        string name = "Data",
        string flags = "",
        string interfaces = "Unity.Entities.IComponentData") => "[Entities.Authoring.AutoAuthoring" + flags + "] public struct " + name + " : " + interfaces + " { " + body + " }";
    private static void Check(bool condition, string name)
    {
        if (!condition)
        {
            throw new Exception("FAIL " + name);
        }

        _passed++;
        Console.WriteLine("PASS " + name);
    }

    private static void Compiles(Result result, string name)
    {
        var errors = result.Compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();

        if (errors.Length > 0)
        {
            throw new Exception(name + "\n" + string.Join("\n", errors.Select(e => e.ToString())));
        }

        Check(!result.Run.Diagnostics.Any(d => d.Severity == DiagnosticSeverity.Error), name);
    }

    private static void Error(
        string source,
        string id,
        string name)
    {
        var result = Run(source);
        Check(result.Run.Diagnostics.Any(d => d.Id == id) &&
            result.Metadata.Length == 0 &&
            result.Baker.Length == 0, name);
    }

